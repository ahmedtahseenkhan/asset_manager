#!/usr/bin/env python3
"""
Vendor-side license signing tool. NEVER ship this (or any private key) to customers.

The application verifies licenses offline with the public key baked into
backend/licensing/public_key.pem — no network access is ever required.

Usage:
    # One-time: generate a keypair
    python sign_license.py keygen --out-dir keys/

    # Issue a license file
    python sign_license.py issue \
        --private-key keys/license_private.pem \
        --customer "Acme Corp" \
        --expires 2027-08-07 \
        --max-assets 1000 --max-users 25 \
        --modules assets,cmdb,contracts,entitlements,notifications,connectors \
        --grace-days 14 \
        --out acme.lic

License file format (JSON):
    {"format": 1, "payload": "<base64 JSON claims>", "signature": "<base64 Ed25519 sig>"}
"""
import argparse
import base64
import json
import sys
import uuid
from datetime import date
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

KNOWN_MODULES = ["assets", "cmdb", "contracts", "entitlements", "notifications", "connectors"]


def cmd_keygen(args: argparse.Namespace) -> None:
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    priv_path = out_dir / "license_private.pem"
    pub_path = out_dir / "license_public.pem"
    if priv_path.exists() and not args.force:
        sys.exit(f"Refusing to overwrite existing {priv_path} (use --force).")

    private_key = Ed25519PrivateKey.generate()
    priv_path.write_bytes(
        private_key.private_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PrivateFormat.PKCS8,
            encryption_algorithm=serialization.NoEncryption(),
        )
    )
    priv_path.chmod(0o600)
    pub_path.write_bytes(
        private_key.public_key().public_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PublicFormat.SubjectPublicKeyInfo,
        )
    )
    print(f"Private key: {priv_path}  (keep offline, chmod 600)")
    print(f"Public key:  {pub_path}  (copy to backend/licensing/public_key.pem)")


def cmd_issue(args: argparse.Namespace) -> None:
    private_key = serialization.load_pem_private_key(
        Path(args.private_key).read_bytes(), password=None
    )
    if not isinstance(private_key, Ed25519PrivateKey):
        sys.exit("Private key must be an Ed25519 key generated by `keygen`.")

    modules = [m.strip() for m in args.modules.split(",") if m.strip()]
    unknown = set(modules) - set(KNOWN_MODULES)
    if unknown:
        sys.exit(f"Unknown modules: {sorted(unknown)}. Known: {KNOWN_MODULES}")

    claims = {
        "license_id": str(uuid.uuid4()),
        "customer": args.customer,
        "issued_at": date.today().isoformat(),
        "expires_at": args.expires,
        "grace_days": args.grace_days,
        "max_assets": args.max_assets,
        "max_users": args.max_users,
        "modules": modules,
    }
    # Sign the exact canonical payload bytes; verifier checks these same bytes.
    payload_bytes = json.dumps(claims, sort_keys=True, separators=(",", ":")).encode()
    signature = private_key.sign(payload_bytes)

    envelope = {
        "format": 1,
        "payload": base64.b64encode(payload_bytes).decode(),
        "signature": base64.b64encode(signature).decode(),
    }
    Path(args.out).write_text(json.dumps(envelope, indent=2) + "\n")
    print(f"Issued license {claims['license_id']} for {args.customer!r} -> {args.out}")
    print(json.dumps(claims, indent=2))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    kg = sub.add_parser("keygen", help="Generate Ed25519 keypair")
    kg.add_argument("--out-dir", default="keys")
    kg.add_argument("--force", action="store_true")
    kg.set_defaults(func=cmd_keygen)

    iss = sub.add_parser("issue", help="Issue a signed license file")
    iss.add_argument("--private-key", required=True)
    iss.add_argument("--customer", required=True)
    iss.add_argument("--expires", required=True, help="YYYY-MM-DD")
    iss.add_argument("--max-assets", type=int, default=500)
    iss.add_argument("--max-users", type=int, default=10)
    iss.add_argument("--grace-days", type=int, default=14)
    iss.add_argument("--modules", default=",".join(KNOWN_MODULES))
    iss.add_argument("--out", required=True)
    iss.set_defaults(func=cmd_issue)

    args = parser.parse_args()
    # Validate date format early
    if args.command == "issue":
        try:
            date.fromisoformat(args.expires)
        except ValueError:
            sys.exit("--expires must be YYYY-MM-DD")
    args.func(args)


if __name__ == "__main__":
    main()
